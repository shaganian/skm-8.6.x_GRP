//**************************************************************************/
//****** Структура базы DS18B20 **********
//
//	[0]		- Код прибора;
//	[1]~[7] - Адрес прибора в сети;
//	[8]		- Значение температуры (Мл.байт)
//	[9]		- Значение температуры (Ст.байт)	
//	[10]	- Верхний порог температуры;
//	[11]	- Нижний порог температуры;
//	[12]	- Регистр конфигурации
//
//**************************************************************************/
//		Карта памяти термометров DS18B20:
//
//	байт0	Значение температуры (Мл.байт)
//	байт1	Значение температуры (Ст.байт)
//	байт2	Верхний порог температуры (сохраняется в EEPROM DS18B20)
//	байт3	Нижний порог температуры (сохраняется в EEPROM DS18B20)
//	байт4	Регистр конфигурации (сохраняется в EEPROM DS18B20)
//	байт5	Неиспользуется (всегда 0хFF)
//	байт6	Неиспользуется (всегда 0х0C)
//	байт7	Неиспользуется (всегда 0х10)
//	байт8	Контрольная сумма CRC
//	
//****************************************************************
// Измерение температуры если в сети несколько приборов
// *После команды на изм.температуры, нужно ждать не менее 0,5 сек.
// параметр mode==0 - читается измерение
// параметр mode==1 - посылается команда на измерение
//
//****** Структура базы DS18B20 **********
//
//	[0]		- Код прибора;
//	[1]~[7] - Адрес прибора в сети;
//	[8]		- Значение температуры (Мл.байт)
//	[9]		- Значение температуры (Ст.байт)	
//	[10]	- Верхний порог температуры;
//	[11]	- Нижний порог температуры;
//	[12]	- Регистр конфигурации
  char in_ds_sensor;
//
char Loop_DS1820_M(unsigned char mode)
{
  
    in_ds_sensor = OWReset();		      // Сбрасываем прибор,
    if (in_ds_sensor == 0) return 11;     // Если приборы отсутствуют, выходим

    if(mode==0){  // Режим чтения измеренных значений.
    
			  OWWriteByte(0xCC);			        // Команда "Пропуск Адреса"
			  OWWriteByte(0xBE);			        // Команда "Читать температуру"
			  ROM_NO[0] = OWReadByte();   // и второй.
			  ROM_NO[1] = OWReadByte();   // Читаем Первый байт
			  ROM_NO[2] = OWReadByte();   // Читаем 3 байт
			  ROM_NO[3] = OWReadByte();   // Читаем 4 байт
			  ROM_NO[4] = OWReadByte();   // Читаем 5 байт
			  ROM_NO[5] = OWReadByte();   // Читаем 6 байт
			  ROM_NO[6] = OWReadByte();   // Читаем 7 байт
			  ROM_NO[7] = OWReadByte();   // Читаем 8 байт
			  ROM_NO[8] = OWReadByte();   // Читаем 9 байт
			  in_ds_sensor = CRC8(&ROM_NO[0], 9);// Формируем Контрольную сумму CRC8
		      __no_operation();

	}
	else if(mode==1){	// Запускаем измерение температуры.

			  OWWriteByte(0xCC);			        // Команда "Пропуск Адреса"
			  OWWriteByte(0x44);			        // Команда "Читать температуру"
			  in_ds_sensor =0;
	}
// После команды на изм.температеры, нужно ждать не менее 0,5 сек.
  return in_ds_sensor;

}
