//**************************************************************************/
// Выполняет Алгоритм Поиска Устройств на шине 1-Wire
// используя существующее состояние поиска.
// Возврат TRUE  : Устройство найдено, номер ROM в буфере ROM_NO
//         FALSE : Устройство не найдено, конец поиска
//
char OWSearch(void)
{
char id_bit_number;
char last_zero, rom_byte_number, search_result;
char id_bit, cmp_id_bit;
unsigned char rom_byte_mask, search_direction;

	// Инициализация поиска
	id_bit_number = 1;
	last_zero = 0;
	rom_byte_number = 0;
	rom_byte_mask = 1;
	search_result = 0;
	crc8 = 0;

    if(!LastDeviceFlag)// Если последний вызов не был последним
    {
        if(!OWReset()) // Сбрасываем 1-Wire
        {
			LastDiscrepancy = 0;		// Сбрасываем переменные поиска
			LastDeviceFlag = FALSE;
			LastFamilyDiscrepancy = 0;
			return FALSE;
		}
        wait_1us(1);         // Пауза
        OWWriteByte(0xF0);				// Запускаем команду поиска
        do								// Выполняем цикл поиска
        {
            id_bit = OWReadBit();		// читаем бит и его дополнение
            cmp_id_bit = OWReadBit();

            if ((id_bit == 1) && (cmp_id_bit == 1)) break;// Проверка на отсутствие устройств на шине 1-wire

            else		// Все устройства в сети могут иметь 0 или 1
            {
                if (id_bit != cmp_id_bit) search_direction = id_bit; // записываем значение бита для поиска
					// ^-- В данной ситуации последовательность может быть 01 или 10.
                else	// Если просходит несовпадение перед последним несовпадением (Last Discrepancy)
                {		// предыдущего, то следующим выбераем такой же как в последней проверке
                    if (id_bit_number < LastDiscrepancy) 
						 search_direction = ((ROM_NO[rom_byte_number] & rom_byte_mask) > 0);
                    else search_direction = (id_bit_number == LastDiscrepancy); // если последний ответ равен, то выбираем 1
																				// если нет, то потом выберем 0

                    if (search_direction == 0)	// Если получился 0, то записывается его позиция в LastZero
                    {
                        last_zero = id_bit_number; //
                        if (last_zero < 9)		// check for Last discrepancy in family
                        LastFamilyDiscrepancy = last_zero;
                    }
                }
                // Устанавливаем или очищаем бит rom_byte_number в ROM
                // используя маску rom_byte_mask
                if (search_direction == 1) ROM_NO[rom_byte_number] |= rom_byte_mask;
                else ROM_NO[rom_byte_number] &= ~rom_byte_mask;

                OWWriteBit(search_direction);	// записываем бит для поиска серийного номера
                id_bit_number++;		// Инкрементируем счетчик быйтов id_bit_number
                rom_byte_mask <<= 1;	// и перемещаем маску rom_byte_mask

                if (rom_byte_mask == 0)	// Если маска = 0, переходим на новый байт Серийного номера rom_byte_number
                {						// и сбрасываем маску
                    docrc8(ROM_NO[rom_byte_number]); // Накапливаем CRC
                    rom_byte_number++;
                    rom_byte_mask = 1;
                }
            }//конец else
        } while(rom_byte_number < 8); // Выполняем цикл для всех байтов ROM bytes 0-7

        // Если поиск выполнен успешно, тогда:
        if (!((id_bit_number < 65) || (crc8 != 0)))
        {
            // Поиск завершен успешно, устанавливаем значения для LastDiscrepancy,LastDeviceFlag,search_result
            LastDiscrepancy = last_zero;
            if (LastDiscrepancy == 0) LastDeviceFlag = TRUE; // Проверяем - было-ли устройство последним
			search_result = TRUE;	// Устанавливаем флаг, что поиск прошел успешно.
        }
    }// end     if (!LastDeviceFlag)

	if (!search_result || !ROM_NO[0])	// Если устройство не найдено, то сбрасываем счетчики
	{									// и следующий поиск будет выполняться как первый (First)
		LastDiscrepancy = 0;
		LastDeviceFlag = FALSE;
		LastFamilyDiscrepancy = 0;
		search_result = FALSE;
	}

	return search_result;
}
