unsigned char OWReadByte(void)
{
unsigned char n, tmp=0;

    for (n=0; n<7; n++){
        if(OWReadBit()==1) tmp+=0x80;
        tmp = tmp >> 1;         // Младший бит заходит первым !!!
    }
    if(OWReadBit()==1) tmp+=0x80;
return tmp;
}
