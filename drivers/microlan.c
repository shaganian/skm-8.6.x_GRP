//**************************************************************************
// Сбрасываем шину 1-Wire и определяем наличие любого устройства
// Return TRUE  : Устройство присутствует
//        FALSE : Устройство отсутствует
//
char OWReset(void)
{
signed int i;
char y=0;
    PJOUT |= BIT2;                          // DRIVE = 1;
    //__delay_cycles(480);                  // выполняем паузу (ждем включения внешнего питания)
    __delay_cycles(600);                  // выполняем паузу (ждем включения внешнего питания)
    PJOUT &= ~BIT2;                         // DRIVE = 0;
    __delay_cycles(5);                  // выполняем паузу (ждем включения внешнего питания)
	i=0;
	while(i < IMP_RST){                     // Ждем Импульс Присутствия 500мкс. Через 50мкс смотрим на SENSE.
	    res_ml = PJIN & 0x08;               // читаем ножку SENSE
		if((i>=IMP_OTV)&&(res_ml==0)){
		    y=1;  // Есть ответ от прибора-фиксируем.
    PJOUT |= BIT2;                          // DRIVE = 1;
		    break;
		}
		i++;
	}
    //__delay_cycles(250);                  // выполняем паузу (ждем включения внешнего питания)
    __delay_cycles(300);                  // выполняем паузу (ждем включения внешнего питания)
    PJOUT &= ~BIT2;                         // DRIVE = 0;
	return y;
}
//**************************************************************************/
// Посылаем 8 битов данных на шину 1-Wire.
//
void OWWriteByte(unsigned char byte_value)
{
unsigned char n;

	for (n=0; n<8; n++){
		if((byte_value & 0x01)==0)  OWWriteBit(0);  // Запись "0"
	    else                        OWWriteBit(1);  // Запись "1"
   		byte_value = byte_value >> 1;
   }
}
//**************************************************************************/
// Посылаем 1 бит данных на шину 1-Wire.
//
void OWWriteBit(unsigned char bit_value)
{

    if (bit_value == 0){            // write_0();// всего ~ 125мкс
	        PJOUT |= BIT2;                      //Запись НУЛЯ!!! - DRIVE = 1;
		   	// Пауза ~ 110мкс
	        __delay_cycles(100);                // формируем импульс
	        PJOUT &= ~BIT2;                     //  DRIVE = 0;
 		   	// Импульс ~ 13мкс
            __delay_cycles(2);                  // отпускаем шину, начинает работать подтяжка кверху
	}
	else{                           //write_1();// всего ~ 120мкс
	        PJOUT |= BIT2;                      // DRIVE = 1;
            // Импульс в 8,5мкс
            __delay_cycles(15);                 // формируем импульс
		   	PJOUT &= ~BIT2;                     // DRIVE = 0;
            // Пауза ~ 110мкс
	        __delay_cycles(85);                 // отпускаем шину, начинает работать подтяжка кверху
	}
}
//**************************************************************************
// Читает 1 бит данных с шины 1-Wire
// Return 1 : Прочитана 1
//        0 : прочитан 0
//
unsigned char OWReadBit(void)
{
    PJOUT |= BIT2;                      // DRIVE = 1;
    // Импульс в 10мкс
    __delay_cycles(5);                  //
    PJOUT &= ~BIT2;                     // DRIVE = 0; отпускаем шину
    // пауза...
    __delay_cycles(10);                 // выполняем паузу перед чтением
    //
    res_ml = PJIN & 0x08;               // читаем ножку SENSE PJ.3
    if (res_ml == 0){        // Чтение "0"
        // Пауза ~ 100мкс
	    __delay_cycles(62);             // выполняем паузу...
        return 0; //
    }
    else {                  // Чтение ЕДИНИЦЫ.
        // Пауза ~ 100мкс
	    __delay_cycles(62);             // выполняем паузу...
        return 1; //
    }
}
//**************************************************************************/
// Читает 1 байт данных с шины 1-Wire
// Return  : Значение Байта
//
unsigned char OWReadByte(void)
{
unsigned char n, tmp=0;

    for (n=0; n<7; n++){
        if(OWReadBit()==1) tmp+=0x80;
        tmp = tmp >> 1;         // Младший бит заходит первым !!!
    }
    if(OWReadBit()==1) tmp+=0x80;
return tmp;
}
