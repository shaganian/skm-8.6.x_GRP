// Проверяет номер устройства с номером в буфере ROM_NO.
// Return TRUE  : Сравниваемое устройство присутствует
//        FALSE : устройство отсутствует
//
char OWVerify(void)
{
unsigned char rom_backup[8];
char i,rslt,ld_backup,ldf_backup,lfd_backup;

	// Сохраняем backup копию текущего состояния
	for (i = 0; i < 8; i++)
		rom_backup[i] = ROM_NO[i];

	ld_backup = LastDiscrepancy;
	ldf_backup = LastDeviceFlag;
	lfd_backup = LastFamilyDiscrepancy;

	// Настраиваем поиск, чтобы найти такое же устройство
	LastDiscrepancy = 64;
	LastDeviceFlag = FALSE;

	if (OWSearch())
	{
		// Проверяем, если такое же устройство найдено
		rslt = TRUE;
		for (i = 0; i < 8; i++)
		{
			if (rom_backup[i] != ROM_NO[i])
			{
				rslt = FALSE;
				break;
			}
		}
	}
	else
		rslt = FALSE;

	// Восстанавливаем состояние поиска
	for (i = 0; i < 8; i++)
		ROM_NO[i] = rom_backup[i];

	LastDiscrepancy = ld_backup;
	LastDeviceFlag = ldf_backup;
	LastFamilyDiscrepancy = lfd_backup;

	// return результат сравнения
	return rslt;
}
//**************************************************************************
// Настраиваем поиск устройства по типу 'family_code
// следующим вызовом OWNext(), если оно присутствует.
//
void OWTargetSetup(unsigned char family_code)
{
char i;
	// Настраиваем состояние на поиск SearchFamily типа устройств
	ROM_NO[0] = family_code;

	for (i = 1; i < 8; i++)
		ROM_NO[i] = 0;

	LastDiscrepancy = 64;     // Последнее Несовпавшие разряды
	LastFamilyDiscrepancy = 0;// Последнее НЕСОВПАДЕНИЕ ГРУППЫ
	LastDeviceFlag = FALSE;   // 
}

//**************************************************************************/
// Настройка поиска, чтобы пропускать текущий тип устройства на следующем
// вызове OWNext().
//
void OWFamilySkipSetup(void)
{
	// Устанавливаем Last discrepancy (Последнее несходство)
	// в последнюю группу несовпадений
	LastDiscrepancy = LastFamilyDiscrepancy;
	LastFamilyDiscrepancy = 0;

	// Проверяем конец списка - check for end of list
	if (LastDiscrepancy == 0)
		LastDeviceFlag = TRUE;
}
