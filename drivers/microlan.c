// Подсчет контрольной суммы по полиному CRC = x^8+x^5+x^4+1
unsigned char CRC8(unsigned char* buf, unsigned char size)
{
unsigned char c = 0;
unsigned char* adr;

    for(adr = buf; size--; adr++)
        c = crc8_table[c ^ *adr];
    return c;
}



