// Посылаем 8 битов данных на шину 1-Wire.
//
void OWWriteByte(unsigned char byte_value)
{
unsigned char n;

	for (n=0; n<8; n++){
		if((byte_value & 0x01)==0)  OWWriteBit(0);  // Запись "0"
	    else                        OWWriteBit(1);  // Запись "1"
   		byte_value = byte_value >> 1; 
   }
}
